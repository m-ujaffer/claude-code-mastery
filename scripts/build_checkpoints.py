#!/usr/bin/env python3
"""Instructor tool: rebuild checkpoints/ and verify the reference solutions.

    uv run python scripts/build_checkpoints.py            # rebuild checkpoints/
    uv run python scripts/build_checkpoints.py --verify   # run every lab check against the solutions

How it works: solutions/weekN/ holds *overlays*. Each overlay mirrors the repo
layout and contains full files as they look at the end of week N.
- A checkpoint for "week-N-start" is the pristine practice-app with the
  practice-app overlays of all earlier weeks applied.
- --verify copies the whole repo to a temp dir, applies every overlay, makes
  the git history some labs expect, and runs `labcheck --all` there.
"""

from __future__ import annotations

import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOLUTIONS = ROOT / "solutions"
CHECKPOINTS = ROOT / "checkpoints"
IGNORE = shutil.ignore_patterns("__pycache__", "*.db", ".pytest_cache", ".venv", ".ruff_cache")

# Which overlays make up the starting point of each week.
STARTS = {2: [1], 3: [1, 2], 4: [1, 2], 5: [1, 2, 4], 6: [1, 2, 4, 5]}


def overlay(src: Path, dest: Path) -> None:
    if src.exists():
        shutil.copytree(src, dest, dirs_exist_ok=True, ignore=IGNORE)


def pristine_practice_app(dest: Path) -> None:
    """Copy practice-app exactly as committed (so instructor edits in progress don't leak)."""
    has_commits = subprocess.run(["git", "rev-parse", "--verify", "-q", "HEAD"], cwd=ROOT,
                                 capture_output=True).returncode == 0
    if has_commits:
        dirty = subprocess.run(["git", "status", "--porcelain", "practice-app"], cwd=ROOT,
                               capture_output=True, text=True).stdout.strip()
        if dirty:
            sys.exit("practice-app/ has uncommitted changes; commit or stash them first.")
    shutil.copytree(ROOT / "practice-app", dest, ignore=IGNORE)


def build_checkpoints() -> None:
    if CHECKPOINTS.exists():
        shutil.rmtree(CHECKPOINTS)
    for week, overlays in STARTS.items():
        dest = CHECKPOINTS / f"week-{week}-start" / "practice-app"
        pristine_practice_app(dest)
        for w in overlays:
            overlay(SOLUTIONS / f"week{w}" / "practice-app", dest)
        print(f"built {dest.relative_to(ROOT)}")
    (CHECKPOINTS / "README.md").write_text(
        "# Checkpoints\n\n"
        "Snapshots of `practice-app/` as it should look at the **start** of each week.\n"
        "Fell behind? Restore one (your current version is backed up to `.backup/` first):\n\n"
        "```bash\nbash scripts/reset_to.sh week-3-start\n```\n\n"
        "Generated by `scripts/build_checkpoints.py`. Do not edit by hand.\n"
    )


def git(cwd: Path, *args: str) -> None:
    subprocess.run(["git", *args], cwd=cwd, check=True, capture_output=True)


def verify() -> int:
    with tempfile.TemporaryDirectory() as tmp:
        work = Path(tmp) / "repo"
        shutil.copytree(ROOT, work, ignore=shutil.ignore_patterns(
            ".git", ".venv", "__pycache__", "*.db", ".pytest_cache", "notes"))
        (work / "notes").mkdir()
        git(work, "init", "-q", "-b", "main")
        git(work, "config", "user.email", "verify@example.com")
        git(work, "config", "user.name", "verify")
        git(work, "add", "-A")
        git(work, "commit", "-q", "-m", "chore: starting point")
        for week in sorted(int(p.name[4:]) for p in SOLUTIONS.glob("week*")):
            overlay(SOLUTIONS / f"week{week}", work)
            if week == 2:  # w2d9 expects a feature branch with a Conventional Commit
                git(work, "checkout", "-q", "-b", "feature/tf-105-completed-at")
                git(work, "add", "-A")
                git(work, "commit", "-q", "-m", "feat(tasks): record completed_at (TF-105)")
                git(work, "checkout", "-q", "main")
                git(work, "merge", "-q", "--no-ff", "-m", "Merge TF-105", "feature/tf-105-completed-at")
            elif week == 5:  # w5d22 expects TF-107 and TF-108 commits plus a merge
                git(work, "checkout", "-q", "-b", "feature/tf-107-108")
                git(work, "add", "-A")
                git(work, "commit", "-q", "-m", "feat(tasks): CSV export (TF-107) and search (TF-108)")
                git(work, "checkout", "-q", "main")
                git(work, "merge", "-q", "--no-ff", "-m", "Merge TF-107 and TF-108", "feature/tf-107-108")
            else:
                git(work, "add", "-A")
                git(work, "commit", "-q", "--allow-empty", "-m", f"chore: week {week} solutions")
        # Executable bits are not always preserved by copies from Windows checkouts.
        for script in (work / "scripts").glob("*.sh"):
            script.chmod(0o755)
        env = {**os.environ, "ANTHROPIC_API_KEY": os.environ.get("ANTHROPIC_API_KEY", "sk-ant-verify-only")}
        proc = subprocess.run([sys.executable, "-m", "labcheck.cli", "--all", "--root", str(work)],
                              cwd=ROOT, env=env)
        return proc.returncode


if __name__ == "__main__":
    if "--verify" in sys.argv:
        sys.exit(verify())
    build_checkpoints()
